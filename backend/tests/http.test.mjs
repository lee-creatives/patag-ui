import test from 'node:test';
import {hashPassword} from '../passwords.mjs';
import assert from 'node:assert/strict';
import { database,fixtures,ids } from './database.mjs';
import { createServer } from '../server.mjs';
const origin='http://127.0.0.1:5173',secret='Shared administrator password 123';
test('HTTP shared accounts: verified login, secure session, validation, paging, details, changes and logout',async()=>{
 const pool=await database();await fixtures(pool.db);await pool.db.exec('DROP SCHEMA auth CASCADE');
 await pool.db.query('UPDATE public.users SET password_hash=$1 WHERE id=$2',[await hashPassword(secret),ids.admin]);
 const config={origin,secure:false};let cookie='';
 const server=createServer({config,pool,storage:{}});await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const base='http://127.0.0.1:'+server.address().port+'/api';
 const send=(path,body,method='POST',headers={})=>fetch(base+path,{method,headers:{Origin:origin,'X-Patag-Request':'1','Content-Type':'application/json',Cookie:cookie,...headers},body:JSON.stringify(body)});
 try {
  assert.equal((await fetch(base+'/health')).status,200);
  assert.equal((await fetch(base+'/users')).status,401);
  assert.equal((await send('/auth/login',{email:'admin@example.test',password:'wrong'})).status,401);
  const login=await send('/auth/login',{email:'admin@example.test',password:secret});assert.equal(login.status,200);
  cookie=login.headers.get('set-cookie').split(';')[0];assert.match(login.headers.get('set-cookie'),/HttpOnly/);
  assert.equal((await login.json()).token,undefined);
  const get=path=>fetch(base+path,{headers:{Cookie:cookie}});
  let r=await send('/users',{name:'HTTP Shared',email:'shared@example.test',role:'citizen',active:true});
  assert.equal(r.status,201);assert.equal(r.headers.get('set-cookie'),null);
  const created=await r.json();assert.equal(created.role,'citizen');
  assert.equal((await pool.db.query('SELECT id FROM public.users WHERE id=$1',[created.id])).rows.length,1);
  assert.equal((await send('/users',{name:'HTTP Shared',email:'SHARED@example.test',role:'citizen',active:true})).status,409);
  r=await get('/users?q=HTTP&role=citizen&active=true&limit=1&offset=0');assert.equal(r.status,200);assert.equal((await r.json()).users[0].id,created.id);
  assert.equal((await get('/users/'+encodeURIComponent(created.id))).status,200);
  assert.equal((await send('/users',{id:created.id,role:'citizen',active:false},'PATCH')).status,200);
  assert.equal((await pool.db.query('SELECT active FROM public.users WHERE id=$1',[created.id])).rows[0].active,false);
  for(const query of ['limit=NaN','offset=-1','role=owner','active=yes','unexpected=1']) assert.equal((await get('/users?'+query)).status,400);
  assert.equal((await get('/users/missing')).status,404);
  for(const id of ['%ZZ','bad%2Fid','%00','a'.repeat(201)]) assert.equal((await get('/users/'+id)).status,400);
  assert.equal((await send('/users',{id:created.id,role:'owner',active:true},'PATCH')).status,400);
  assert.equal((await send('/users',{id:created.id,role:'citizen',active:'false'},'PATCH')).status,400);
  assert.equal((await send('/users',{name:'x',email:'x@example.test',role:'citizen',active:true,password_hash:'bad'})).status,400);
  assert.equal((await send('/users',{},'POST',{Origin:'https://evil.test'})).status,403);
  await pool.db.query('UPDATE public.users SET active=false WHERE id=$1',[ids.admin]);assert.equal((await get('/users')).status,401);
  assert.equal((await send('/auth/logout',{})).status,200);
  assert.equal((await get('/users')).status,401);
  for(const path of ['/auth/recovery','/auth/password','/auth/mfa']) assert.equal((await send(path,{})).status,404);
 }finally{await new Promise(r=>server.close(r));await pool.end();}
});
